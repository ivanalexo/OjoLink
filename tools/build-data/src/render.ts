export function header(source: string, version: string): string {
  return `// Generated by @ojolink/build-data. Do not edit.
// Source: ${source}
// Source version: ${version}
`;
}

/** Version label for curated files: the most recent date an entry was checked. */
export function latestDate(dates: readonly string[]): string {
  return [...dates].sort().at(-1) ?? "unknown";
}
