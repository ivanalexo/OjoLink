import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { build, loadSources, OUTPUT_DIR } from "../src/build.ts";

const normalize = (text: string) => text.replaceAll("\r\n", "\n");
const sources = loadSources();
const { files, summary } = build(sources);

describe("generated datasets", () => {
  it.each(Object.keys(files))("%s is up to date with its sources", (name) => {
    const path = join(OUTPUT_DIR, name);
    const onDisk = existsSync(path) ? normalize(readFileSync(path, "utf8")) : "";
    const stale = onDisk !== normalize(files[name] ?? "");
    expect(
      stale ? `${name} is stale: run "pnpm --filter @ojolink/build-data generate"` : "up to date",
    ).toBe("up to date");
  });

  it("is deterministic", () => {
    expect(build(loadSources()).files).toEqual(files);
  });

  it("records the source and version in every file", () => {
    for (const content of Object.values(files)) {
      expect(content).toMatch(
        /^\/\/ Generated by @ojolink\/build-data\. Do not edit\.\n\/\/ Source: .+\n\/\/ Source version: \S+\n/,
      );
    }
  });

  it("detects a curated change that was not regenerated", () => {
    const [bo] = sources.protected;
    if (!bo) throw new Error("bo.json is missing");
    const edited = {
      ...sources,
      protected: [
        {
          ...bo,
          content: {
            ...bo.content,
            entities: bo.content.entities.filter((entity) => entity.domain !== "bcp.com.bo"),
          },
        },
      ],
    };
    const onDisk = normalize(readFileSync(join(OUTPUT_DIR, "protected-domains.ts"), "utf8"));
    expect(build(edited).files["protected-domains.ts"]).not.toBe(onDisk);
  });
});

describe("curated Bolivia pack", () => {
  const [bo] = sources.protected;

  it("lists the 22 entities of the requirements document, one of them unconfirmed", () => {
    expect(bo?.content.entities).toHaveLength(22);
    const pending = bo?.content.entities.filter(
      (entity) => entity.verification.status === "unconfirmed",
    );
    expect(pending?.map((entity) => entity.domain)).toEqual(["bdp.com.bo"]);
  });

  it("does not list the tax office's subdomain separately", () => {
    const domains = bo?.content.entities.map((entity) => entity.domain);
    expect(domains).toContain("impuestos.gob.bo");
    expect(domains).not.toContain("siat.impuestos.gob.bo");
  });

  it("reports what was left out", () => {
    expect(summary.filter((line) => line.startsWith("left out"))).toEqual([
      "left out (unconfirmed): bo: bancodecredito.com.bo (BCP)",
      "left out (unconfirmed): bo: bancoganadero.com.bo (Banco Ganadero)",
      "left out (unconfirmed): bo: bancomercantil.com.bo (Banco Mercantil Santa Cruz)",
      "left out (unconfirmed): bo: bdp.com.bo (BDP)",
    ]);
  });
});
